						if ([ ${detected_pattern[0]} != ${pattern[0]} ] || [ ${detected_pattern[2]} != ${pattern[2]} ] || [ $((detected_pattern[1] - pattern[1])) -gt 2 ] || [ $((pattern[1] - detected_pattern[1])) -gt 2 ]);then
							str="***WARNING: Detected input waveform pattern (${detected_pattern[@]}) seems different than configured pattern (${pattern[@]})"
							print_msg="${print_msg}${str}\n"
							warning_list="$warning_list$str\n"
						fi
						fi
					fi
					fi
					invecfile_ori[$txant]=$invecfile
					[ $no_wv_load = 0 ] && invecfile_cur[$txant]=$invecfile
				else
					if [ $no_wv_load = 0 ];then
						str="***WARNING: Input waveform file $invecfile does not exist,\n            waveform not loaded. Users can run ./update_test_vector.sh <filename> to load it later."
						print_msg="${print_msg}${str}\n"
						warning_list="$warning_list$str\n"
					fi
				fi
				([ $no_wv_load = 0 ] && [ $test_vector_on_hram = 0 ]) && { pci_bw_req_total=$((pci_bw_req_total+baseband_txsps*32)); pci_bw_req[$txant]=$((baseband_txsps*32)); }
			fi
			invecsize_backup=$invecsize
			invecfile_backup=$invecfile
			invec_addr_cur_backup=$invec_addr_phy
		fi
		
		if [ $((rxant)) -eq $((0xF)) ];then
			((dfe_mode_msb=dfe_mode_msb|(1<<23)))  #disable RX
			rxant=0   #compose msg with ant id 0 since RX is disabled
		elif ([ $((ant_selected[rxant]&BITMASK_ANT_ENABLE_RX)) = 0 ] || [ $txonly = 1 ]);then
			((dfe_mode_msb=dfe_mode_msb|(1<<23)))  #disable RX
		else
			get_chan_para $rxant $core; [ $? -ne 0 ] && channels_start_fail
			option8_rx[$rxant]=$option8rx;
			bbsps_rx[rxant]=$baseband_rxsps
			axiqsps_rx[rxant]=$rxaxiq
			sinad_enable_arr[rxant]=$sinad_enable
			if [ $((rxant2)) -ne $((0xF)) ];then
			option8_rx[$rxant2]=$option8rx;
			bbsps_rx[rxant2]=$baseband_rxsps
			axiqsps_rx[rxant2]=$rxaxiq
			sinad_enable_arr[rxant2]=$sinad_enable
			fi
			if [ $rxant -lt 4 ];then
				rxdcs_ls=$rxdcs
				scs_ls=$scs
			else
				rxdcs_hs=$rxdcs
				scs_hs=$scs
			fi	

			if [ $((${DCSchan[${ant_map_rx[$rxant]}]}&BITMASK_ANT_ENABLE_RX)) -eq 0 ]; then
				((dfe_mode_msb=dfe_mode_msb|(1<<23)))  #disable RX
			fi
		fi
		
		[ $(((dfe_mode_msb&((1<<22)|(1<<23))))) -eq $(((1<<22)|(1<<23))) ] && continue  #both TX and RX disabled
		
		dfe_mode_msb=$(( dfe_mode_msb|no_rx_sym_to_host|(lphy<<9)|(option8<<8)|(dfe_only<<1) )) #set no RX sym and lowPHY only
		((dfe_mode_msb=dfe_mode_msb|0x0E000000|((1-ecpri_comp_decomp_enable)<<7)|(txrestart<<20)|(rxrestart<<21)|(bypass_handshake_rx<<DFE_MODE_RX_HANDSHAKE_BYPASS_IDX)|(bypass_handshake_tx<<DFE_MODE_TX_HANDSHAKE_BYPASS_IDX)))
		((dfe_mode_lsb=dfe_mode_lsb+(iqswap_tx[ant_map_tx[txant]] << 19)+(iqswap_rx[ant_map_rx[rxant]] << 23)))
		[ $((txant2)) -ne $((0xF)) ] && ((dfe_mode_lsb=dfe_mode_lsb+(iqswap_tx[ant_map_tx[txant2]] << 3)))
		[ $((rxant2)) -ne $((0xF)) ] && ((dfe_mode_lsb=dfe_mode_lsb+(iqswap_rx[ant_map_rx[rxant2]] << 7)))
		((dfe_mode_lsb=dfe_mode_lsb+(rx_allowed_ext<<12)))
		
		[ $((ant_map_tx[$txant])) -ge 6 ] && { echo ERROR config in TX ant re-mapping: DCS channel number ${ant_map_tx[$txant]} is illegal; echo; channels_start_fail; }
		[ $((ant_map_rx[$rxant])) -ge 6 ] && { echo ERROR config in RX ant re-mapping: DCS channel number ${ant_map_rx[$rxant]} is illegal; echo; channels_start_fail; }


		if [ $((txant_ori)) -eq $((0xF)) ];then dcs_id_tx=7
		elif ([ $((ant_selected[txant_ori]&BITMASK_ANT_ENABLE_TX)) = 0 ] || [ $rxonly = 1 ]);then dcs_id_tx=$((ant_map_tx[$txant_ori])) #dcs_id_tx=7
		elif [ $((${DCSchan[${ant_map_tx[$txant_ori]}]}&BITMASK_ANT_ENABLE_TX)) -eq 0 ];then dcs_id_tx=$((ant_map_tx[$txant_ori])) #dcs_id_tx=7
		else 
			dcs_id_tx=$((ant_map_tx[$txant_ori]))
			if [ $txant_ori -lt 4 ];then ((num_T_LS_enabled++)) 
			else ((num_T_HS_enabled++)) 
			fi
			dcs_enable[dcs_id_tx]=$((dcs_enable[dcs_id_tx]+BITMASK_ANT_ENABLE_TX))
			ant_enable[txant_ori]=$((ant_enable[txant_ori]+BITMASK_ANT_ENABLE_TX))
		fi
		
		if [ $((rxant_ori)) -eq $((0xF)) ];then dcs_id_rx=7
		elif ([ $((ant_selected[rxant_ori]&BITMASK_ANT_ENABLE_RX)) = 0 ] || [ $txonly = 1 ]);then dcs_id_rx=$((ant_map_rx[$rxant_ori])) #dcs_id_rx=7
		elif [ $((${DCSchan[${ant_map_rx[$rxant_ori]}]}&BITMASK_ANT_ENABLE_RX)) -eq 0 ];then dcs_id_rx=$((ant_map_rx[$rxant_ori])) #dcs_id_rx=7
		else 
			dcs_id_rx=$((ant_map_rx[$rxant_ori]))
			if [ $rxant_ori -lt 4 ];then ((num_R_LS_enabled++)) 
			else ((num_R_HS_enabled++))
			fi
			dcs_enable[dcs_id_rx]=$((dcs_enable[dcs_id_rx]+BITMASK_ANT_ENABLE_RX))
			ant_enable[rxant_ori]=$((ant_enable[rxant_ori]+BITMASK_ANT_ENABLE_RX))
		fi
		
		if [ $((txant2)) -eq $((0xF)) ];then dcs_id_tx2=7
		elif ([ $((ant_selected[txant2]&BITMASK_ANT_ENABLE_TX)) = 0 ] || [ $rxonly = 1 ]);then dcs_id_tx2=7
		elif [ $((${DCSchan[${ant_map_tx[$txant2]}]}&BITMASK_ANT_ENABLE_TX)) -eq 0 ];then dcs_id_tx2=7
		else 
			dcs_id_tx2=$((ant_map_tx[$txant2]))
			if [ $txant2 -lt 4 ];then ((num_T_LS_enabled++)) 
			else ((num_T_HS_enabled++)) 
			fi
			dcs_enable[dcs_id_tx2]=$((dcs_enable[dcs_id_tx2]+BITMASK_ANT_ENABLE_TX))
			ant_enable[txant2]=$((ant_enable[txant2]+BITMASK_ANT_ENABLE_TX))
		fi
		
		if [ $((rxant2)) -eq $((0xF)) ];then dcs_id_rx2=7
		elif ([ $((ant_selected[rxant2]&BITMASK_ANT_ENABLE_RX)) = 0 ] || [ $txonly = 1 ]);then dcs_id_rx2=7
		elif [ $((${DCSchan[${ant_map_rx[$rxant2]}]}&BITMASK_ANT_ENABLE_RX)) -eq 0 ];then dcs_id_rx2=7
		else 
			dcs_id_rx2=$((ant_map_rx[$rxant2]))
			if [ $rxant2 -lt 4 ];then ((num_R_LS_enabled++)) 
			else ((num_R_HS_enabled++))
			fi
			dcs_enable[dcs_id_rx2]=$((dcs_enable[dcs_id_rx2]+BITMASK_ANT_ENABLE_RX))
			ant_enable[rxant2]=$((ant_enable[rxant2]+BITMASK_ANT_ENABLE_RX))
		fi
		
		((dfe_mode_lsb=dfe_mode_lsb|(dcs_id_tx << 16)|(dcs_id_tx2 << 0)))
		((dfe_mode_lsb=dfe_mode_lsb|(dcs_id_rx << 20)|(dcs_id_rx2 << 4)))
		dfe_mode_msb=$((dfe_mode_msb | (hwdcm<<6) | (bwdiv<<4) | (hsdiv2<<3) | (lsdiv2<<2) ))
		dfe_mode_msb=`HEX $dfe_mode_msb`; dfe_mode_lsb=`HEX $dfe_mode_lsb`
		
		sym_buf_size=`size_align $((sym_size*4)) 128`
		sym_buf_config_msb=`printf "0x%08X" $(( 0x10000000 + ((num_sym_in_queue_rx/2)<<20) + (rx_sym_queue_base>>12) ))`
		sym_buf_config_lsb=`printf "0x%08X" $(( (((sym_buf_size/128)&0xFF)<<24) + ((num_sym_in_queue_tx/2)<<20) + (tx_sym_queue_base>>12) ))`
		txcore=$core #${anttx[$ant]}
		rxcore=$core #${antrx[$ant]}
		one_enabled_dfe_core=$core
		tid=${tidant[$txant]}
		rid=${ridant[$rxant]}
		inject_msb=`size_align $((sym_size*4)) 128`
		inject_msb=`printf "0x%08x" $((0x0A110000 + (inject_msb/128) + (tid<<15)))`
		inject_lsb=`printf "0x%08x" $(((sym_num<<20)+(${addr_tx_wv[$txant]}>>12)))`
		
		if ([ $extlog = 1 ] && [ $txant = 0 ]);then    #setup external log buffer for ant0 only.
		set_wordvalue_to_vspa $core $ext_log_buf_base $((trace_log_buf_base+core*trace_log_buf_size_per_core))
		set_wordvalue_to_vspa $core $ext_log_buf_size $((trace_log_buf_size_per_core))
		score=$((slave_core[core]))
		if [ $score != $core ];then
		set_wordvalue_to_vspa $score $ext_log_buf_base $((trace_log_buf_base+score*trace_log_buf_size_per_core))
		set_wordvalue_to_vspa $score $ext_log_buf_size $((trace_log_buf_size_per_core))
		fi
		fi
		
		
		if ([ $tx_fdd = 0 ] && [ $dcsfdd = 1 ] && [ $vspa_dev_type = LA9310 ]);then
			if [ $((${#pattern[@]} % 6)) -eq 0 ];then
			num_sym_in_slot=14
			for ((i=0;i<${#pattern[@]};i=i+6))
			do
				skip0=0
				dlsym=$((  pattern[0+i]*num_sym_in_slot+pattern[1+i]  ))
				skip1=$(( (pattern[2+i]*num_sym_in_slot+pattern[3+i]) + ((num_sym_in_slot-pattern[1+i]-pattern[3+i])%num_sym_in_slot) + (num_sym_in_slot*pattern[4+i]) + (num_sym_in_slot*pattern[5+i]) ))
				pattern_size_dl=$(( (skip1<<16) + (dlsym<<8) + skip0 ))
				
				skip0=$(( (pattern[0+i]*num_sym_in_slot+pattern[1+i]) + ((num_sym_in_slot-pattern[1+i]-pattern[3+i])%num_sym_in_slot) + (num_sym_in_slot*pattern[4+i]) ))
				ulsym=$((  pattern[2+i]*num_sym_in_slot+pattern[3+i]  ))
				skip1=$((  num_sym_in_slot*pattern[5+i] ))
				pattern_size_ul=$(( (skip1<<16) + (ulsym<<8) + skip0 ))
				
				[ $cpe = 0 ] && { pattern_size_tx=$pattern_size_dl; pattern_size_rx=$pattern_size_ul; } || { pattern_size_rx=$pattern_size_dl; pattern_size_tx=$pattern_size_ul; }
				
				set_wordvalue_to_vspa $txcore $((tx_pattern_entry+i/6*4)) $pattern_size_tx
				set_wordvalue_to_vspa $txcore $((rx_pattern_entry+i/6*4)) $pattern_size_rx
			done
			set_wordvalue_to_vspa $txcore $num_patterns $((i/6)) #set num of entries
			
			elif [ $((${#pattern[@]} % 4)) -eq 0 ];then
			for ((i=0;i<${#pattern[@]};i=i+4))
			do
				skip0=0
				dlsym=$((  pattern[0+i]  ))
				skip1=$((  pattern[1+i] + pattern[2+i] +  pattern[3+i] ))
				pattern_size_dl=$(( (skip1<<16) + (dlsym<<8) + skip0 ))
				
				skip0=$((  pattern[0+i] + pattern[1+i] ))
				ulsym=$((  pattern[2+i]  ))
				skip1=$((  pattern[3+i]  ))
				pattern_size_ul=$(( (skip1<<16) + (ulsym<<8) + skip0 ))
				
				[ $cpe = 0 ] && { pattern_size_tx=$pattern_size_dl; pattern_size_rx=$pattern_size_ul; } || { pattern_size_rx=$pattern_size_dl; pattern_size_tx=$pattern_size_ul; }
				
				set_wordvalue_to_vspa $txcore $((tx_pattern_entry+i/4*4)) $pattern_size_tx
				set_wordvalue_to_vspa $txcore $((rx_pattern_entry+i/4*4)) $pattern_size_rx
			done
			set_wordvalue_to_vspa $txcore $num_patterns $((i/4)) #set num of entries
			fi
		fi
		

		
		#send 1st init msg: SYMBOL BUFFER STRUCT
		echo "./utils/vspa_mbox send $txcore $host_vspa_mbox_id $sym_buf_config_msb $sym_buf_config_lsb; ./utils/vspa_mbox recv $txcore $host_vspa_mbox_id" >> ./command_init.sh
		vspa_mbox_ifsend $txcore $host_vspa_mbox_id $sym_buf_config_msb $sym_buf_config_lsb; [ $msg_recv_flag = 0 ] && vspa_mbox_ifrecv $txcore $host_vspa_mbox_id
		./utils/memrw w 32 $((test_tool_env_buf_struct_msg+txcore*8+0)) $sym_buf_config_msb $((test_tool_env_buf_struct_msg+txcore*8+4)) $sym_buf_config_lsb
		print_msg="${print_msg}Sending SYMBOL BUFFER STRUCT message to core $txcore: vspa_mbox send $txcore $host_vspa_mbox_id $sym_buf_config_msb $sym_buf_config_lsb, "
		([ $msg_recv_flag = 0 ] || [ $((msg_recv_msb32&0xFF000000)) -ne $((0x11000000)) ]) && { echo -e "$print_msg"; echo "***ERROR: VSPA core $txcore did not respond to Buffer struct config msg."; channels_start_fail; }
		print_msg="${print_msg}ACK MSB:$msg_recv_msb32 LSB:$msg_recv_lsb32\n"
		
		if [ $dfe_only = 0 ];then
		if ([ $((idle)) = 1 ] || [ $((dfe_mode_msb&(1<<22))) -ne 0 ]); then  #set single tone mode with amp=0 for idle or channel not enabled
			print_msg="${print_msg}Setting TX channel to idle state to core $txcore    : vspa_mbox send $txcore $host_vspa_mbox_id 0x0a0e0000 0x40000000\n"
			echo ./utils/vspa_mbox send $txcore $host_vspa_mbox_id 0x0a0e0000 0x40000000 >> ./command_init.sh
			vspa_mbox_ifsend $txcore $host_vspa_mbox_id 0x0a0e0000 0x40000000
		fi
		if ([ $((type_ru | force_ru)) -eq $((1)) ] && [ $cell_state != $CELL_STATE_SEARCH ] && [ $sinad = 0 ] && [ $((dfe_mode_msb&(1<<22))) -eq 0 ] && [ $rt = 0 ]); then
			print_msg="${print_msg}Sending INJECT DL TEST VECTOR msg to core $txcore   : vspa_mbox send $txcore $host_vspa_mbox_id $inject_msb $inject_lsb\n"
			echo ./utils/vspa_mbox send $txcore $host_vspa_mbox_id $inject_msb $inject_lsb >> ./command_init.sh
			inject_freq_domain_tx $txcore $host_vspa_mbox_id $inject_msb $inject_lsb
		fi
		fi
		
		if ([ $size_inject_rx -ne 0 ] && [ $((dfe_mode_msb&(1<<23))) -eq 0 ]);then
			score=$((slave_core[core]))
			block_size_axiq=$((block_size*downsampling_ratio))
			size_inject_rx=$((size_inject_rx/block_size_axiq*block_size_axiq)) #align inject size to block size.
			set_wordvalue_to_vspa $score $rx_inject_addr $addr_inject_rx
			set_wordvalue_to_vspa $score $rx_inject_size $size_inject_rx
			echo RX time domain inject configured for ant $rxant from address `HEX $addr_inject_rx` size $size_inject_rx
		fi
		
		#send 2nd init msg: DFE MODE
		echo "./utils/vspa_mbox send $txcore $host_vspa_mbox_id $dfe_mode_msb $dfe_mode_lsb; ./utils/vspa_mbox recv $txcore $host_vspa_mbox_id" >> ./command_init.sh
		vspa_mbox_ifsend $txcore $host_vspa_mbox_id $dfe_mode_msb $dfe_mode_lsb; [ $msg_recv_flag = 0 ] && vspa_mbox_ifrecv $txcore $host_vspa_mbox_id
		./utils/memrw w 32 $((test_tool_env_dfe_mode_msg+txcore*8+0)) $dfe_mode_msb $((test_tool_env_dfe_mode_msg+txcore*8+4)) $dfe_mode_lsb
		([ $msg_recv_flag = 0 ] || [ $((msg_recv_msb32&0xFF000000)) -ne $((0x0F000000)) ]) && { echo -e "$print_msg"; echo "***ERROR: VSPA core $txcore did not respond to DFE mode msg."; channels_start_fail; }
		print_msg="${print_msg}Sending DFE MODE CONFIG message to core $txcore     : vspa_mbox send $txcore $host_vspa_mbox_id `HEX $dfe_mode_msb` `HEX $dfe_mode_lsb`, ACK MSB:$msg_recv_msb32 LSB:$msg_recv_lsb32\n"

		#send 3rd init msg: STATIC SLOT FORMAT if needed
		if [ $vspa_dev_type = LA12xx ];then
		if [ $((tx_fdd&rx_fdd)) = 0 ];then
		echo "./utils/vspa_mbox send $txcore $host_vspa_mbox_id $pattern_msg1 $pattern_msg0; ./utils/vspa_mbox recv $txcore $host_vspa_mbox_id" >> ./command_init.sh
		vspa_mbox_ifsend $txcore $host_vspa_mbox_id $pattern_msg1 $pattern_msg0; [ $msg_recv_flag = 0 ] && vspa_mbox_ifrecv $txcore $host_vspa_mbox_id
		print_msg="${print_msg}Sending SLOT PATTERN CONFIG message to core $txcore : vspa_mbox send $txcore $host_vspa_mbox_id $pattern_msg1 $pattern_msg0, "
		([ $msg_recv_flag = 0 ] || [ $((msg_recv_msb32&0xFF000000)) -ne $((0x13000000)) ]) && { echo -e "$print_msg"; echo "***ERROR: VSPA core $txcore did not respond to Slot pattern config msg."; channels_start_fail; }
		print_msg="${print_msg}ACK MSB:$msg_recv_msb32 LSB:$msg_recv_lsb32\n"
		fi
		fi

		
		#check vspa initialized status
		swversion=`./utils/memrw r 32 $((modembase_phy+0x1000000+core*0x4000+4))`
		((flag_dfe_initialized=(swversion>>12)&1))
		if [ $flag_dfe_initialized = 0 ];then
			echo -e "$print_msg"
			echo -e "***ERROR: VSPA initialization failed on core $core, SWVERSION_REG=$swversion\n"; exit 1
			channels_start_fail
		fi
	done

	[ $fast = 0 ] && echo -e "$print_msg"
	[ $((num_T_LS_enabled+num_T_HS_enabled+num_R_LS_enabled+num_R_HS_enabled)) -eq 0 ] && { echo -e "\n***ERROR: No channel is started, the ant_id you specified does not exist.\n"; channels_start_fail; }
	if ([ $num_T_LS_enabled -gt 2 ] && [ $num_R_LS_enabled -gt 2 ] && [ $((tx_fdd|dcsfdd)) = 1 ] && [ $bandwidth -eq 100 ] && [ $((lphy+dfe_only)) -eq 0 ]);then
		str="***WARNING: For 100Mhz, 2T2R/4T/4R FDD or 4T4R TDD are supported with full functinalities. \nYou are running more than 2T2R FDD, the system is set with reduced functionalities in RX.\nDisabled: RX Down sampling filter, RX low pass filter, RX FFT\nEnabled: RX QEC, RX time domain Dumping"
		warning_list="$warning_list$str\n"
		for((i=0;i<NUM_CORES;i++))
		do
		[ $((dfe_core[i])) = 0 ] && continue
		kernel_disable $i $KERNELS_DISABLE_BITMASK_RX_FFT $KERNELS_DISABLE_BITMASK_RX_FFT
		kernel_disable $i $KERNELS_DISABLE_BITMASK_RX_LPF $KERNELS_DISABLE_BITMASK_RX_LPF
		kernel_disable $i $KERNELS_DISABLE_BITMASK_DOWNSAMPLING $KERNELS_DISABLE_BITMASK_DOWNSAMPLING
		done
	fi
	
	if [ $test_vector_on_hram = 1 ];then
		if [ $((tv_malloc_cur)) -ge $((HRAMaddr_phy+HRAM_size)) ];then
			echo ***ERROR: Input test vector exceeds HRAM size; channels_start_fail
		fi
		next_HRAMaddr_phy=$tv_malloc_cur
	else
		ddr_malloc_cur=$tv_malloc_cur
	fi
	size_tx_test_vector=$((tv_malloc_cur-addr_tx_test_vector))
	addr_dump=$ddr_malloc_cur; addr_dump_vir=`phy2vir $addr_dump`
	ddr_malloc_cur=`printf 0x%x $((ddr_malloc_cur + size_dump))` 
	end_ddr=$ddr_malloc_cur
	addr_inject_tx=$addr_dump; size_inject_tx=0;
	
	if [ $((end_ddr)) -gt $((ddr_phy+ddr_size)) ];then
		str="***WARNING: DDR size larger than available. Size needed `printf "0x%x" $((end_ddr-ddr_phy))`, size available `printf "0x%x" $ddr_size`"
		echo $str; warning_list="$warning_list$str\n"
	fi
	
	
	echo "loopback=$loopback; rloopback_time=$rloopback_time; rloopback_freq=$rloopback_freq; num_errors=0; first_error=0" > runtime_config.txt
	echo "ant_remap=$ant_remap; ant_map_tx=(${ant_map_tx[@]}); ant_map_rx=(${ant_map_rx[@]})" >> ./runtime_config.txt
	echo -e "DCSchan=(${DCSchan[@]})\ndfe_core=(${dfe_core[@]}); slave_core=(${slave_core[@]}); one_dfe_core=$one_dfe_core\ntest_tool_name=$test_tool_name; test_tool_version=$test_tool_version; vspa_image_version=$vspa_image_version; revision=$revision; ver_min=$ver_min; ver_maj=$ver_maj\niqswap_tx=(${iqswap_tx[@]}); iqswap_rx=(${iqswap_rx[@]}); MAX_NUM_1R_IN_CORE=$MAX_NUM_1R_IN_CORE" >> ./runtime_config.txt
	echo -e "anttx=(${anttx[@]}); antrx=(${antrx[@]}); coretx_tr0=(${coretx_tr0[@]}); corerx_tr0=(${corerx_tr0[@]})\ncoretx_tr1=(${coretx_tr1[@]}); corerx_tr1=(${corerx_tr1[@]});" >> ./runtime_config.txt
	echo -e "fr1_used=$fr1_used; fr2_used=$fr2_used\nnum_T_LS=$num_T_LS; num_T_HS=$num_T_HS; num_R_LS=$num_R_LS; num_R_HS=$num_R_HS\ntidcore=(${tidcore[@]}); ridcore=(${ridcore[@]}); tidant=(${tidant[@]}); ridant=(${ridant[@]}); idle=$idle; sinad=$sinad " >> ./runtime_config.txt
