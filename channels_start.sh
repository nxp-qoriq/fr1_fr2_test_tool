		echo $e200_cmd_tool -c "l1c config pattern $str_pattern"
		sleep $l1c_sleep_time
		
		$e200_cmd_tool -c "l1c config ul_dl_gap $ul_dl_gap"
		echo $e200_cmd_tool -c "l1c config ul_dl_gap $ul_dl_gap"
		sleep $l1c_sleep_time

		$e200_cmd_tool -c "l1c config pps_offset 0"
		echo $e200_cmd_tool -c "l1c config pps_offset 0"
		sleep $l1c_sleep_time
	
		if ([ $rx_fdd = 1 ] || [ $((rx_allowed_ext)) -eq 15 ]);then                              #enable RX FDD in LS or HS
			$e200_cmd_tool -c "l1c config listen yes"
			echo $e200_cmd_tool -c "l1c config listen yes"
			sleep $l1c_sleep_time
		fi

		tag_l1c_start_cpe=(no_vspa_start start_cpe)
		$e200_cmd_tool -c "l1c ${tag_l1c_start_cpe[cpe]}"
		echo $e200_cmd_tool -c "l1c ${tag_l1c_start_cpe[cpe]}"
		echo "L1C start command sent to e200 at VSPA core timestamp $(printf 0x%012x `get_counter vspa $one_dfe_core`)"

		if [ $((l1c)) = 1 ];then  #if LS is TDD, HS will be configured as FDD.
			master_counter_hs=$(get_tbgen_master_counter "HS")
			elapse_l1c=$((master_counter_hs - startoffset_hs))
			elapse_l1c=$((elapse_l1c/tbgen2_freq + 2))                   #add more seconds
			startoffset_hs=$((startoffset_hs + elapse_l1c*tbgen2_freq))  #as L1C TDD config cost too much time, reset start offset
			for((dcsid=NUM_ANTS_LS;dcsid<NUM_ANTS;dcsid++))
			do
				trx_enable=${dcs_enable[$dcsid]}
				[ $trx_enable -eq 0 ] && continue
				if ([ $((trx_enable & BITMASK_ANT_ENABLE_TX)) -ne 0 ] || [ $rx_fdd = 0 ]);then
					str="***WARNING: Current L1C does not support TDD on LS+HS concurrently. Only LS TDD will be enabled. HSDCS$((dcsid-4)) will be configured as FDD.\n"
					echo -e "$str";
					warning_list="$warning_list$str\n"
				fi
				value=${tag[$trx_enable]}
				echo -e "Enabling HSDCS$((dcsid-4)) $value in FDD mode, with ${elapse_l1c}s additional start offset.\n"
				set_tbgen_offset "HS" $((dcsid-4)) $value $startoffset_hs
			done
		fi
		
		one_enabled_dcsid_ctrl_reg=$(get_tdd_ctrl ${TAG_LSHS[$one_enabled_dcsid_by_l1c]} $((one_enabled_dcsid_by_l1c%4)) )
		one_enabled_dcsid_ctrl_reg_v=`./utils/memrw r 32 $one_enabled_dcsid_ctrl_reg`
		wait_count=1000
		while ([ $((one_enabled_dcsid_ctrl_reg_v&1)) -eq 0 ] && [ $wait_count -ne 0 ])
		do
			one_enabled_dcsid_ctrl_reg_v=`./utils/memrw r 32 $one_enabled_dcsid_ctrl_reg`
			wait_count=$((wait_count-1))
			[ $wait_count -eq 0 ] && { echo Timeout waiting e200 L1C TDD logic to enable DCS.; channels_start_fail; }
		done
		l1c_startoffset=$(( (`./utils/memrw r 32 $((one_enabled_dcsid_ctrl_reg+4))`<<32) | `./utils/memrw r 32 $((one_enabled_dcsid_ctrl_reg+8))`))
		echo "l1c will start from TBGEN master counter offset $(printf 0x%x $l1c_startoffset)"
		echo Waiting till tbgen start for l1c...; wait_till_tbgen_tick ${TAG_LSHS[$one_enabled_dcsid_by_l1c]} $((l1c_startoffset+1*tbgen1_freq))

	else
		echo Waiting till tbgen start for FDD mode...; wait_till_tbgen_tick $startoffset_set $startoffset_value

	fi
fi
fi

./check_all.sh

[ $((lphy|use_nxp_l1c)) = 0 ] && echo -e "Waiting for DCS to be enabled. Users have configured to use their own software to enable DCS. \n"
[ "$warning_list" != "" ] && echo -e "$warning_list"
exit 0
